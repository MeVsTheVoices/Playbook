import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

process.chdir(fileURLToPath(new URL(".", import.meta.url)));
const check = process.argv.includes("--check");
const result = await build({
  entryPoints: ["frontend/structured_output.js"],
  outfile: "static/structured_output.js",
  bundle: true,
  minify: true,
  write: false,
  legalComments: "none",
  banner: { js: "/* Generated by build_frontend.mjs. Licenses: structured_output.LICENSE.txt */" },
});
const licenses = await Promise.all(["highlight.js", "json-stringify-pretty-compact"].map(async name =>
  `${name}\n\n${await readFile(`node_modules/${name}/LICENSE`, "utf8")}`
));
const assets = new Map([
  ["static/structured_output.js", result.outputFiles[0].text],
  ["static/structured_output.LICENSE.txt", licenses.join("\n\n")],
]);
for (const [path, content] of assets) {
  if (check) {
    const saved = await readFile(path, "utf8");
    if (saved !== content) throw new Error(`Stale ${path}; run npm run build in callback_site.`);
  } else {
    await writeFile(path, content);
  }
}
console.log(check ? "Frontend assets are up to date." : "Built frontend assets and license notices.");
