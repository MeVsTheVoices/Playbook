"""Compile the portal's Sass entrypoints without a Flask runtime dependency."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
import tempfile

APP_DIR = Path(__file__).resolve().parent
GENERATED_HEADER = "/* Generated by build_styles.py; edit styles/ instead. */\n"


def build_styles(source_dir: Path, output_dir: Path, *, check: bool = False) -> int:
    try:
        from sass_embedded import compile_file
    except ModuleNotFoundError as exc:
        if exc.name != "sass_embedded":
            raise
        print(
            "Missing Dart Sass compiler. Install callback_site/requirements-styles.txt.",
            file=sys.stderr,
        )
        return 1

    sources = sorted(path for path in source_dir.glob("*.scss") if not path.name.startswith("_"))
    if not sources:
        print(f"No Sass entrypoints found in {source_dir}", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory(prefix="callback-styles-") as tmp:
        compiled: dict[str, str] = {}
        for source in sources:
            target = Path(tmp) / source.with_suffix(".css").name
            result = compile_file(source, target, no_sourcemap=True)
            if not result.ok:
                print(f"Sass compilation failed for {source.name}:\n{result.error}", file=sys.stderr)
                return 1
            compiled[target.name] = GENERATED_HEADER + target.read_text(encoding="utf-8")

        stale = [
            name for name, text in compiled.items()
            if not (output_dir / name).exists()
            or (output_dir / name).read_text(encoding="utf-8") != text
        ]
        if check:
            if stale:
                print("Stale generated CSS: " + ", ".join(stale), file=sys.stderr)
                print("Run python callback_site/build_styles.py and include the CSS changes.", file=sys.stderr)
                return 1
            print(f"All {len(compiled)} stylesheets are up to date.")
            return 0

        output_dir.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".styles-", dir=output_dir) as staging:
            for name in stale:
                target = Path(staging) / name
                target.write_text(compiled[name], encoding="utf-8")
                target.replace(output_dir / name)
        print(f"Built {len(compiled)} stylesheets ({len(stale)} updated).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated CSS is missing or stale.")
    args = parser.parse_args()
    return build_styles(APP_DIR / "styles", APP_DIR / "static", check=args.check)


if __name__ == "__main__":
    sys.exit(main())
